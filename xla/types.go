// Column describes a table column at the version of the record that references it.
type Column struct {
	Name       string
	Type       DataType
	Size       int // declared size (characters or bytes)
	Precision  int
	Scale      int
	Nullable   bool
	PrimaryKey bool
	SysColNum  int // 1-based column number (SYS.COLUMNS.COLNUM)
}

// Table is a table definition at one version. Records of the same version share one *Table;
// treat it as read-only.
type Table struct {
	Owner      string
	Name       string
	SysTableID uint64
	Version    int64
	Columns    []Column
	PrimaryKey []int // indexes into Columns, in key order
	index      map[string]int
}

// QualifiedName returns OWNER.NAME.
func (t *Table) QualifiedName() string { return t.Owner + "." + t.Name }

// ColumnIndex returns the index of a column by (case-sensitive, normally upper-case) name, or -1.
func (t *Table) ColumnIndex(name string) int {
	if i, ok := t.index[name]; ok {
		return i
	}
	return -1
}

// Kind is the representation of a Value.
type Kind int

const (
	KindNull      Kind = iota
	KindInt            // Int
	KindFloat          // Float (BINARY_FLOAT, BINARY_DOUBLE)
	KindDecimal        // Text holds an exact decimal number (NUMBER, FLOAT, DECIMAL)
	KindString         // Text (character types in the connection character set; ROWID)
	KindBytes          // Bytes (BINARY, VARBINARY)
	KindTime           // Time (DATE, TIMESTAMP)
	KindTimeOfDay      // Time on 0000-01-01 (TIME)
	KindLOB            // a non-NULL LOB: XLA does not deliver LOB contents
)

// Value is one column value of a row image.
type Value struct {
	Kind  Kind
	Int   int64
	Float float64
	Text  string
	Bytes []byte
	Time  time.Time
}

// IsNull reports whether the value is SQL NULL.
func (v Value) IsNull() bool { return v.Kind == KindNull }

// Any returns the value as int64, float64, string, []byte, time.Time or nil. Decimals are returned
// as their exact text; LOBs as nil.
func (v Value) Any() any {
	switch v.Kind {
	case KindInt:
		return v.Int
	case KindFloat:
		return v.Float
	case KindDecimal, KindString:
		return v.Text
	case KindBytes:
		return v.Bytes
	case KindTime, KindTimeOfDay:
		return v.Time
	}
	return nil
}

// String renders the value for logs.
func (v Value) String() string {
	switch v.Kind {
	case KindNull:
		return "NULL"
	case KindLOB:
		return "<LOB>"
	case KindBytes:
		return fmt.Sprintf("0x%X", v.Bytes)
	case KindTime:
		return v.Time.Format("2006-01-02 15:04:05.999999999")
	case KindTimeOfDay:
		return v.Time.Format("15:04:05")
	}
	return fmt.Sprint(v.Any())
}

// LSN is the log position of a record (ordering only; records of one transaction may share it).
type LSN struct{ File, Offset uint64 }

// Record is one committed change read from the transaction log.
type Record struct {
	Op         Op
	Flags      Flags
	TxnID      uint64 // TimesTen transaction id (unique among concurrently active transactions)
	ConnID     uint64 // id of the connection that made the change
	LSN        LSN
	SysTableID uint64
	Owner      string // table owner (DML, TRUNCATE, most DDL)
	Name       string // table name
	Table      *Table // table definition for DML records; nil otherwise
	Old        []Value
	New        []Value
	// UpdatedColumns lists indexes (into Table.Columns) of columns changed by an UPDATE.
	UpdatedColumns []int
}

// FirstInTxn reports whether the record starts a transaction.
func (r *Record) FirstInTxn() bool { return r.Flags&FlagFirst != 0 }

// EndsTxn reports whether the record is the last one of its transaction (implied commit).
func (r *Record) EndsTxn() bool { return r.Flags&FlagCommit != 0 }

// QualifiedName returns OWNER.NAME of the affected table.
func (r *Record) QualifiedName() string {
	if r.Owner == "" {
		return r.Name
	}
	return r.Owner + "." + r.Name
}

// OldValue / NewValue return a column of the before / after image by name.
func (r *Record) OldValue(col string) (Value, bool) { return r.valueOf(r.Old, col) }
func (r *Record) NewValue(col string) (Value, bool) { return r.valueOf(r.New, col) }

func (r *Record) valueOf(row []Value, col string) (Value, bool) {
	if r.Table == nil || row == nil {
		return Value{}, false
	}
	i := r.Table.ColumnIndex(col)
	if i < 0 {
		return Value{}, false
	}
	return row[i], true
}

// Key returns the primary key values of the row (after image for INSERT/UPDATE, before image for DELETE).
func (r *Record) Key() []Value {
	if r.Table == nil {
		return nil
	}
	row := r.New
	if r.Op == OpDelete {
		row = r.Old
	}
	if row == nil {
		return nil
	}
	k := make([]Value, len(r.Table.PrimaryKey))
	for i, idx := range r.Table.PrimaryKey {
		k[i] = row[idx]
	}
	return k
}
