// Op is the kind of a transaction log record.
type Op int

const (
	OpInsert      = Op(cli.XlaInsert)
	OpUpdate      = Op(cli.XlaUpdate)
	OpDelete      = Op(cli.XlaDelete)
	OpTruncate    = Op(cli.XlaTruncate)
	OpCommitOnly  = Op(cli.XlaCommitOnly)
	OpCreateTable = Op(cli.XlaCreateTable)
	OpDropTable   = Op(cli.XlaDropTable)
	OpAddColumns  = Op(cli.XlaAddColumns)
	OpDropColumns = Op(cli.XlaDropColumns)
	OpCreateIndex = Op(cli.XlaCreateIndex)
	OpDropIndex   = Op(cli.XlaDropIndex)
	OpCreateView  = Op(cli.XlaCreateView)
	OpDropView    = Op(cli.XlaDropView)
	OpCreateSeq   = Op(cli.XlaCreateSeq)
	OpDropSeq     = Op(cli.XlaDropSeq)
	OpCreateSyn   = Op(cli.XlaCreateSyn)
	OpDropSyn     = Op(cli.XlaDropSyn)
)

var opNames = map[Op]string{
	OpInsert: "INSERT", OpUpdate: "UPDATE", OpDelete: "DELETE", OpTruncate: "TRUNCATE",
	OpCommitOnly: "COMMIT", OpCreateTable: "CREATE TABLE", OpDropTable: "DROP TABLE",
	OpAddColumns: "ADD COLUMNS", OpDropColumns: "DROP COLUMNS", OpCreateIndex: "CREATE INDEX",
	OpDropIndex: "DROP INDEX", OpCreateView: "CREATE VIEW", OpDropView: "DROP VIEW",
	OpCreateSeq: "CREATE SEQUENCE", OpDropSeq: "DROP SEQUENCE", OpCreateSyn: "CREATE SYNONYM",
	OpDropSyn: "DROP SYNONYM",
}

func (o Op) String() string {
	if s, ok := opNames[o]; ok {
		return s
	}
	return "OP(" + strconv.Itoa(int(o)) + ")"
}

// IsDML reports whether the record carries row images (INSERT, UPDATE, DELETE).
func (o Op) IsDML() bool { return o == OpInsert || o == OpUpdate || o == OpDelete }

// Flags are the record flag bits.
type Flags int

const (
	FlagCommit        = Flags(cli.XlaFlagCommit)  // last record of its transaction
	FlagFirst         = Flags(cli.XlaFlagFirst)   // first record of its transaction
	FlagReplicated    = Flags(cli.XlaFlagRepl)    // produced by TimesTen replication from another database
	FlagColumnList    = Flags(cli.XlaFlagCols)    // UPDATE carries the list of changed columns
	FlagDefaults      = Flags(cli.XlaFlagDefault) // CREATE TABLE / ADD COLUMNS carry default values
	FlagCascadeDelete = Flags(cli.XlaFlagCascDel) // delete generated by ON DELETE CASCADE
	FlagAging         = Flags(cli.XlaFlagAging)   // delete generated by table aging
)

